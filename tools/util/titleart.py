"""Pack the title-screen backgrounds into src/js/50a-title-art.js (base64 WebP, so the game stays a single file).

Usage: python3 tools/titleart.py <folder of PNGs>
The folder holds NN-name-desktop.png (16:9) and NN-name-phone.png (portrait) pairs, as rendered for v5.2.
Desktop images are scaled to 1440x810 and phone images to 640 wide, WebP quality 58 (the title blurs and
vignettes them, so this is plenty), plus a 320x180 thumbnail per scene for the map picker (v5.2 review: the picker
used to decode four full desktop images for its small tiles).
"""
import base64, io, pathlib, sys
from PIL import Image

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parents[2] / "src" / "js" / "50a-title-art.js"
names = sorted({p.name.rsplit("-", 1)[0] for p in src.glob("*-desktop.png")})
def pack(p, size, q=58):
    im = Image.open(p).convert("RGB").resize(size, Image.LANCZOS)
    b = io.BytesIO(); im.save(b, "WEBP", quality=q, method=6)
    return "data:image/webp;base64," + base64.b64encode(b.getvalue()).decode()
rows = []
for n in names:
    d = pack(src / f"{n}-desktop.png", (1440, 810)); t = pack(src / f"{n}-desktop.png", (320, 180), 62)
    ph = Image.open(src / f"{n}-phone.png"); w = 640; h = round(ph.height * w / ph.width)
    p = pack(src / f"{n}-phone.png", (w, h))
    rows.append(f'  {{id:"{n.split("-", 1)[1]}",t:"{t}",d:"{d}",\n   p:"{p}"}}')
out.write_text("/* ---------- v5.2 title screen backgrounds (generated by tools/titleart.py; do not edit by hand) ----------\n"
               "   Five scenes rendered from the game, each as a 16:9 desktop frame and a portrait phone frame. One is picked at\n"
               "   random on each page load (51d-title.js). */\nconst TITLE_ART=[\n" + ",\n".join(rows) + "];\n")
print(f"wrote {out} ({out.stat().st_size:,} bytes, {len(rows)} scenes)")
